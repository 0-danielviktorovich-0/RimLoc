// `ui_warn!` expands `is_terminal()` at the call site — the trait must be
// in scope here.
use std::io::IsTerminal as _;

#[allow(dead_code)]
#[allow(clippy::too_many_arguments)]
pub fn run_build_mod(
    po: Option<std::path::PathBuf>,
    out_mod: std::path::PathBuf,
    lang: String,
    from_root: Option<std::path::PathBuf>,
    from_game_version: Option<Vec<String>>,
    name: String,
    package_id: String,
    rw_version: String,
    lang_dir: Option<String>,
    dry_run: bool,
    dedupe: bool,
    merge: bool,
    skip_empty: bool,
) -> color_eyre::Result<()> {
    // build-mod source contract: exactly one of `--po` / `--from-root` (both
    // feed the same `--out-mod`). clap enforces this at parse time; the guard
    // below keeps direct callers of this API honest too.
    if from_root.is_some() && po.is_some() {
        color_eyre::eyre::bail!("{}", crate::tr!("build-po-xor-from-root"));
    }
    if from_root.is_none() && po.is_none() {
        color_eyre::eyre::bail!("{}", crate::tr!("build-source-required"));
    }
    tracing::debug!(event = "build_mod_args", po = ?po, out_mod = ?out_mod, lang = %lang, from_root = ?from_root, from_game_version = ?from_game_version, name = %name, package_id = %package_id, rw_version = %rw_version, lang_dir = ?lang_dir, dry_run = dry_run, merge = merge, skip_empty = skip_empty);
    let cfg = rimloc_config::load_config().unwrap_or_default();
    let cfg_build = cfg.build.unwrap_or_default();
    let lang_folder = lang_dir
        .or(cfg_build.lang_dir)
        .unwrap_or_else(|| rimloc_import_po::rimworld_lang_dir(&lang));
    let name = if name.is_empty() {
        cfg_build
            .name
            .unwrap_or_else(|| "RimLoc Translation".to_string())
    } else {
        name
    };
    let package_id = if package_id.is_empty() {
        cfg_build
            .package_id
            .unwrap_or_else(|| "yourname.rimloc.translation".to_string())
    } else {
        package_id
    };
    let rw_version = if rw_version.is_empty() {
        cfg_build.rw_version.unwrap_or_else(|| "1.5".to_string())
    } else {
        rw_version
    };
    let dedupe = dedupe || cfg_build.dedupe.unwrap_or(false);
    let from_game_version = if from_game_version.is_none() {
        cfg_build.from_root_versions
    } else {
        from_game_version
    };

    // M6: a build into an EXISTING non-empty out dir used to merge silently
    // with the previous build — files the source no longer produces stayed
    // behind and shipped dead keys. Refuse unless `--merge` makes the
    // overwrite-with-keep semantics conscious. Dry-run writes nothing, so
    // planning into an existing dir stays allowed.
    if !dry_run {
        ensure_out_target(&out_mod, merge)?;
    }

    if let Some(root) = from_root {
        // Build from existing Languages/<lang> structure under `root`.
        if dry_run {
            ui_out!("build-dry-run-header");
            ui_out!("build-name", value = name.as_str());
            ui_out!("build-package-id", value = package_id.as_str());
            ui_out!("build-rw-version", value = rw_version.as_str());
            ui_out!("build-mod-folder", value = out_mod.display().to_string());
            ui_out!("build-language", value = lang_folder.as_str());
        }

        let (files, total_keys) = rimloc_services::build_from_root(
            &root,
            &out_mod,
            &lang_folder,
            from_game_version.as_deref(),
            !dry_run,
            dedupe,
            skip_empty,
        )?;
        if dry_run {
            for (path, n) in files {
                ui_out!(
                    "import-dry-run-line",
                    path = path.display().to_string(),
                    n = n
                );
            }
            ui_out!("build-divider");
            ui_out!("build-summary", n = total_keys);
        } else {
            // Minimal About.xml
            let about_dir = out_mod.join("About");
            let _ = std::fs::create_dir_all(&about_dir);
            let about_xml = about_dir.join("About.xml");
            // H4: About.xml fields are user-controlled text — escaped.
            let _ = std::fs::write(&about_xml, format!(
                "<ModMetaData>\n  <packageId>{}</packageId>\n  <name>{}</name>\n  <description>Translation mod (generated by RimLoc)</description>\n  <supportedVersions>\n    <li>{}</li>\n  </supportedVersions>\n</ModMetaData>\n",
                rimloc_core::xml_chars::escape_text(&package_id),
                rimloc_core::xml_chars::escape_text(&name),
                rimloc_core::xml_chars::escape_text(&rw_version)));
            ui_ok!("build-done", out = out_mod.display().to_string());
        }
        return Ok(());
    }

    // Root mode returned above; here the contract validated at the top
    // guarantees `--po` is present.
    let po = po.expect("--po is required when --from-root is absent");

    if dry_run {
        let plan = rimloc_services::build_from_po_dry_run(
            &po,
            &out_mod,
            &lang_folder,
            &name,
            &package_id,
            &rw_version,
            dedupe,
            skip_empty,
        )?;
        ui_out!("build-dry-run-header");
        ui_out!("build-name", value = plan.mod_name);
        ui_out!("build-package-id", value = plan.package_id);
        ui_out!("build-rw-version", value = plan.rw_version);
        ui_out!(
            "build-mod-folder",
            value = plan.out_mod.display().to_string()
        );
        ui_out!("build-language", value = plan.lang_dir);
        ui_out!("build-divider");
        for (path, n) in plan.files {
            ui_out!(
                "import-dry-run-line",
                path = path.display().to_string(),
                n = n
            );
        }
        ui_out!("build-divider");
        ui_out!("build-summary", n = plan.total_keys);
    } else {
        rimloc_services::build_from_po_execute(
            &po,
            &out_mod,
            &lang_folder,
            &name,
            &package_id,
            &rw_version,
            dedupe,
            skip_empty,
        )?;
        ui_ok!("build-done", out = out_mod.display().to_string());
    }
    Ok(())
}

/// M6 out-target honesty: refuse a build into an existing NON-EMPTY
/// directory unless the caller passed `--merge`; with `--merge` warn that
/// stale files are kept (merge never cleans up).
fn ensure_out_target(out_mod: &std::path::Path, merge: bool) -> color_eyre::Result<()> {
    if !out_mod.is_dir() {
        return Ok(());
    }
    let non_empty = std::fs::read_dir(out_mod)
        .map(|mut entries| entries.next().is_some())
        .unwrap_or(false);
    if !non_empty {
        return Ok(());
    }
    if !merge {
        color_eyre::eyre::bail!(
            "{}",
            crate::tr!("build-out-not-empty", out = out_mod.display().to_string())
        );
    }
    crate::ui_warn!("build-merge-warning", out = out_mod.display().to_string());
    Ok(())
}
